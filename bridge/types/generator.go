// Helpers
// ---------------------------------------------------------------------------

// hasBridgeExport checks whether a comment group contains a standalone
// "bridge:export" directive (the comment text must be exactly "// bridge:export"
// or start with "// bridge:export " to avoid false positives from prose).
func hasBridgeExport(cg *ast.CommentGroup) bool {
	if cg == nil {
		return false
	}
	for _, c := range cg.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if text == "bridge:export" || strings.HasPrefix(text, "bridge:export ") {
			return true
		}
	}
	return false
}

// resolveType converts a Go AST type expression to a TypeScript type string.
func resolveType(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		if ts, ok := goToTS[t.Name]; ok {
			return ts
		}
		return t.Name

	case *ast.SelectorExpr:
		full := fmt.Sprintf("%s.%s", t.X, t.Sel.Name)
		if ts, ok := goToTS[full]; ok {
			return ts
		}
		return t.Sel.Name

	case *ast.ArrayType:
		elem := resolveType(t.Elt)
		return elem + "[]"

	case *ast.StarExpr:
		inner := resolveType(t.X)
		return inner + " | undefined"

	case *ast.MapType:
		key := resolveType(t.Key)
		val := resolveType(t.Value)
		return fmt.Sprintf("Record<%s, %s>", key, val)

	case *ast.InterfaceType:
		return "unknown"

	default:
		return "unknown"
	}
}

// parseJSONTag extracts the field name and omitempty flag from a struct tag.
func parseJSONTag(tagValue string) (name string, omitempty bool) {
	tag := strings.Trim(tagValue, "`")
	for _, part := range strings.Split(tag, " ") {
		part = strings.TrimSpace(part)
		if !strings.HasPrefix(part, `json:"`) {
			continue
		}
		val := strings.TrimPrefix(part, `json:"`)
		val = strings.TrimSuffix(val, `"`)
		parts := strings.Split(val, ",")
		name = parts[0]
		for _, p := range parts[1:] {
			if p == "omitempty" {
				omitempty = true
			}
		}
		return
	}
	return "", false
}

// extractDoc pulls the text from a comment group, stripping comment markers.
func extractDoc(cg *ast.CommentGroup) string {
	if cg == nil {
		return ""
	}
	var parts []string
	for _, c := range cg.List {
		text := c.Text
		text = strings.TrimPrefix(text, "//")
		text = strings.TrimPrefix(text, "/*")
		text = strings.TrimSuffix(text, "*/")
		text = strings.TrimSpace(text)
		if text != "" && !strings.HasPrefix(text, "bridge:") {
			parts = append(parts, text)
		}
	}
	return strings.Join(parts, " ")
}
